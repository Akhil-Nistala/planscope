"""Generate the synthetic dataset.

Usage::

    python -m data_gen.generate --out data/synth                       # full run from configs/synth.yaml
    python -m data_gen.generate --out data/synth_small --n 40 --workers 4
    python -m data_gen.generate --out data/synth --overwrite           # regenerate into an existing dir

Layout of ``--out``::

    dataset.yaml                    Ultralytics OBB dataset file (absolute path, class names)
    images/{train,val,test}/*.png|jpg
    labels/{train,val,test}/*.txt   YOLO-OBB: class x1 y1 x2 y2 x3 y3 x4 y4 (normalised)
    gt/*.json                       schema-valid ground-truth documents (src/schema.json)
    meta/*.json                     generation parameters + true text of every region
    pdf/*.pdf                       source PDFs of vector / outlined sheets (if save_pdf)
    manifest.jsonl                  one line per sheet (meta without the region texts)
    summary.json                    counts per split / mode / language / class, router agreement
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import shutil
import time
from collections import Counter
from multiprocessing import Pool
from pathlib import Path
from typing import Any, Sequence

import yaml

from src.config import load_config
from src.detect import CLASSES

from .config import SPLITS, SynthConfig, load_synth_config, load_vocab
from .sheet import SheetResult, generate_sheet

log = logging.getLogger(__name__)
OUTPUT_DIRS = ("images", "labels", "gt", "meta", "pdf", "previews")
OUTPUT_FILES = ("dataset.yaml", "manifest.jsonl", "summary.json")

_W: dict[str, Any] = {}  # per-worker state


def _init_worker(cfg: SynthConfig, out: Path, router_cfg) -> None:
    _W.update(cfg=cfg, out=out, vocab=load_vocab(), router=router_cfg)


def write_sheet(res: SheetResult, out: Path) -> None:
    """Write all files of one sheet."""
    m = res.meta
    for rel, data in ((m["image"], res.image), (m["pdf"], res.pdf)):
        if rel and data is not None:
            (out / rel).write_bytes(data)
    (out / m["label"]).write_text(res.labels, encoding="utf-8")
    # compact JSON: indentation roughly doubles the size of word-heavy GT files
    (out / m["gt"]).write_text(json.dumps(res.gt, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    (out / "meta" / f"{res.spec.id}.json").write_text(json.dumps(m, ensure_ascii=False, separators=(",", ":")),
                                                      encoding="utf-8")


def _work(index: int) -> dict[str, Any]:
    t0 = time.perf_counter()
    try:
        res = generate_sheet(index, _W["cfg"], _W["vocab"], _W["router"])
        write_sheet(res, _W["out"])
    except Exception as e:  # keep the run going; failures are reported in the summary
        logging.getLogger(__name__).exception("sheet %d failed", index)
        return {"index": index, "error": f"{type(e).__name__}: {e}"}
    rec = {k: v for k, v in res.meta.items() if k != "regions"}
    rec["seconds"] = round(time.perf_counter() - t0, 3)
    return rec


def prepare_out(out: Path, overwrite: bool) -> None:
    """Create the output tree. Refuses a non-empty directory unless ``overwrite`` (which removes only
    the generator's own sub-directories and files)."""
    if out.exists() and any(out.iterdir()):
        if not overwrite:
            raise SystemExit(f"{out} is not empty; pass --overwrite to regenerate")
        for d in OUTPUT_DIRS:
            shutil.rmtree(out / d, ignore_errors=True)
        for f in OUTPUT_FILES:
            (out / f).unlink(missing_ok=True)
    for d in ("images", "labels"):
        for s in SPLITS:
            (out / d / s).mkdir(parents=True, exist_ok=True)
    for d in ("gt", "meta", "pdf"):
        (out / d).mkdir(parents=True, exist_ok=True)


def write_dataset_yaml(out: Path) -> None:
    """Ultralytics dataset file. ``path`` is absolute so training works from any working directory."""
    data = {"path": out.resolve().as_posix(), "train": "images/train", "val": "images/val", "test": "images/test",
            "names": dict(enumerate(CLASSES))}
    (out / "dataset.yaml").write_text("# Generated by data_gen.generate -- PlanScope synthetic OBB dataset\n"
                                      + yaml.safe_dump(data, sort_keys=False, allow_unicode=True), encoding="utf-8")


def summarise(records: list[dict[str, Any]], seconds: float, cfg: SynthConfig) -> dict[str, Any]:
    """Aggregate counts for summary.json."""
    ok = [r for r in records if "error" not in r]
    routed = [r for r in ok if r.get("router")]
    classes = Counter()
    for r in ok:
        classes.update(r["class_counts"])
    return {
        "seed": cfg.seed, "requested": cfg.n_sheets, "generated": len(ok),
        "failed": [r for r in records if "error" in r],
        "seconds": round(seconds, 1), "sheets_per_s": round(len(ok) / seconds, 3) if seconds else None,
        "splits": dict(Counter(r["split"] for r in ok)), "modes": dict(Counter(r["mode"] for r in ok)),
        "langs": dict(Counter(r["lang"] for r in ok)), "sheet_sizes": dict(Counter(r["sheet_size"] for r in ok)),
        "layouts": dict(Counter(r["layout"] for r in ok)),
        "instances": {c: classes.get(c, 0) for c in CLASSES},
        "instances_per_split": {s: {c: sum(r["class_counts"][c] for r in ok if r["split"] == s) for c in CLASSES}
                                for s in SPLITS},
        "router_agreement": {
            "checked": len(routed), "agree": sum(r["router"]["agrees"] for r in routed),
            "disagree_ids": [r["id"] for r in routed if not r["router"]["agrees"]],
        },
    }


def run(cfg: SynthConfig, out: Path, workers: int | None = None, overwrite: bool = False,
        progress: bool = True) -> dict[str, Any]:
    """Generate ``cfg.n_sheets`` sheets into ``out`` and return the summary."""
    prepare_out(out, overwrite)
    router_cfg = load_config().router  # the same thresholds the pipeline uses
    n_workers = workers if workers is not None else (cfg.workers or max(1, (os.cpu_count() or 2) - 1))
    n_workers = max(1, min(n_workers, cfg.n_sheets))
    t0 = time.perf_counter()
    records: list[dict[str, Any]] = []
    indices = range(cfg.n_sheets)
    if n_workers == 1:
        _init_worker(cfg, out, router_cfg)
        it = map(_work, indices)
        pool = None
    else:
        pool = Pool(n_workers, initializer=_init_worker, initargs=(cfg, out, router_cfg))
        it = pool.imap_unordered(_work, indices, chunksize=2)
    try:
        for rec in it:
            records.append(rec)
            if progress and (len(records) % 25 == 0 or len(records) == cfg.n_sheets):
                el = time.perf_counter() - t0
                print(f"  {len(records):5d}/{cfg.n_sheets} sheets  {el:7.1f}s  "
                      f"eta {el / len(records) * (cfg.n_sheets - len(records)):7.1f}s", flush=True)
    except BaseException:
        if pool is not None:  # Ctrl+C or a crash in the main process: don't wait for queued sheets
            pool.terminate()
            pool.join()
        raise
    if pool is not None:
        pool.close()
        pool.join()
    seconds = time.perf_counter() - t0

    records.sort(key=lambda r: r["index"])
    with (out / "manifest.jsonl").open("w", encoding="utf-8") as fh:
        for r in records:
            if "error" not in r:
                fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    write_dataset_yaml(out)
    summary = summarise(records, seconds, cfg)
    (out / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    return summary


def main(argv: Sequence[str] | None = None) -> None:
    """CLI entry point."""
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--config", type=Path, default=None, help="default: configs/synth.yaml")
    ap.add_argument("--n", type=int, default=None, help="override n_sheets")
    ap.add_argument("--seed", type=int, default=None, help="override seed")
    ap.add_argument("--workers", type=int, default=None, help="override workers (1 = no multiprocessing)")
    ap.add_argument("--overwrite", action="store_true", help="replace generator outputs already in --out")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO if args.verbose else logging.WARNING,
                        format="%(levelname)s %(name)s: %(message)s")
    cfg = load_synth_config(args.config)
    if args.n is not None:
        cfg.n_sheets = args.n
    if args.seed is not None:
        cfg.seed = args.seed
    cfg.validate()
    s = run(cfg, args.out, args.workers, args.overwrite)
    ra = s["router_agreement"]
    print(f"generated {s['generated']}/{s['requested']} sheets in {s['seconds']}s -> {args.out}")
    print(f"  splits {s['splits']}  modes {s['modes']}")
    print(f"  instances {s['instances']}")
    print(f"  router agrees on {ra['agree']}/{ra['checked']} PDF sheets; failures: {len(s['failed'])}")


if __name__ == "__main__":
    main()
